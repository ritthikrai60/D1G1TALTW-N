import sys
sys.path.insert(0, '.')
from scripts.inspect_paths import load_pdf_doc, extract_subpaths
import json
import math

doc = load_pdf_doc()['document']
layers = {l['name']: l for l in doc['layers']}

X0 = 1000.0
Y0 = 1500.0
SCALE = 28.3464567

def to_m(pt):
    return (round((pt[0] - X0) / SCALE, 3), round(-(pt[1] - Y0) / SCALE, 3))

# 1. SLAB POLYGON
with open('scripts/build_full_ingetrazo_ground_floor.py', 'r', encoding='utf-8') as f:
    text = f.read()

import re
slab_match = re.search(r'slab_poly\s*=\s*(\[.*?\])\n', text, re.DOTALL)
slab_poly = eval(slab_match.group(1))

# 2. COLUMNS (all 77 columns)
cols = []
for lname in ['A-col', 'P-1']:
    l = layers.get(lname)
    if not l: continue
    for i, c in enumerate(l['kind']['children']):
        sps = extract_subpaths(c)
        for sp in sps:
            pts = [to_m(p) for p in sp['anchors']]
            if len(pts) >= 4:
                xs = [p[0] for p in pts]
                ys = [p[1] for p in pts]
                dx = max(xs) - min(xs)
                dy = max(ys) - min(ys)
                if 0.25 <= dx <= 2.0 and 0.25 <= dy <= 2.0:
                    cols.append({
                        'name': f"Col_{len(cols):02d}_{lname}_{i}",
                        'pts': pts,
                        'bbox': (min(xs), min(ys), max(xs), max(ys))
                    })

lines = [
    "# Accurate Complete Basement Model (Columns, Slab, ST-1, ST-2, ST-3)",
    "# Generated by Antigravity",
    "",
    "# CLEAR ALL EXISTING OBJECTS",
    "for g in list(groups):",
    "    erase(g)",
    "for f in list(faces):",
    "    erase(f)",
    "for e in list(edges):",
    "    erase(e)",
    "",
    "# 1. SINGLE UNIFIED FLAT BASEMENT SLAB (Z = 0.00m, thickness 0.20m, 4043.59 m^2)",
    f"slab_poly = {slab_poly}",
    "g_slab = extrude(slab_poly, -0.20, 0.0, name='Basement_Floor_Slab', color=(0.88, 0.88, 0.86, 1.0))",
    "g_slab.layer = 'Slab'",
    "",
    "# 2. ALL 77 STRUCTURAL COLUMNS (height 3.50m from Z = 0.00m to 3.50m)"
]

for i, col in enumerate(cols):
    pts_str = str(col['pts'])
    name = col['name']
    lines.append(f"g_col_{i} = extrude({pts_str}, 0.0, 3.50, name='{name}', color=(0.42, 0.45, 0.50, 1.0))")
    lines.append(f"g_col_{i}.layer = 'Columns'")

lines.extend([
    "",
    "# 3. ST-1: PRIMARY FIRE EGRESS STAIR CORE (Layer P-2 (0.15))",
    "# Location: X in [6.1, 9.5], Y in [3.5, 6.2]",
    "# West Flight: 5 steps climbing North from Z = 0.00m",
    "# Step dimensions: width ~ 1.50m, tread ~ 0.25m, riser ~ 0.175m",
])

# ST-1 West flight: 5 steps
for s in range(5):
    z = round(s * 0.175, 3)
    y_center = 5.05 + s * 0.25
    lines.append(f"box((6.15, {y_center:.3f}, 0.00), (1.50, 0.28, {z + 0.175:.3f}), name='ST1_West_Step_{s+1}', color=(0.80, 0.75, 0.70, 1.0))")

# ST-1 Mid Landing at North (Z = 0.875m)
lines.append("box((6.15, 6.25, 0.00), (3.30, 1.20, 0.875), name='ST1_Mid_Landing', color=(0.80, 0.75, 0.70, 1.0))")

# ST-1 East Flight: returning South (overhead/continuation to 1st Floor, from Z = 0.875m up to 2.625m)
for s in range(10):
    z = round(0.875 + s * 0.175, 3)
    y_center = 5.85 - s * 0.25
    lines.append(f"box((7.75, {y_center:.3f}, 0.00), (1.50, 0.28, {z + 0.175:.3f}), name='ST1_East_Step_{s+1}', color=(0.80, 0.75, 0.70, 1.0))")

lines.extend([
    "",
    "# 4. ST-2: CENTRAL OPEN STAIR NEAR LOCKERS (Layer A-stair)",
    "# Location: X in [7.9, 10.6], Y in [-13.2, -9.0]",
    "# Flight 1: 4 Entrance steps stepping East from Z = 0.00m to lower landing Z = 0.70m",
])

# ST-2 entrance steps: 4 steps stepping East
for s in range(4):
    z = round(s * 0.175, 3)
    x_pos = round(8.00 + s * 0.25, 3)
    lines.append(f"box(({x_pos:.3f}, -13.15, 0.00), (0.28, 1.45, {z + 0.175:.3f}), name='ST2_Entrance_Step_{s+1}', color=(0.75, 0.78, 0.82, 1.0))")

# ST-2 Lower Landing (Z = 0.70m)
lines.append("box((8.85, -13.15, 0.00), (1.50, 1.65, 0.70), name='ST2_Lower_Landing', color=(0.75, 0.78, 0.82, 1.0))")

# ST-2 Main Flight: 10 steps climbing North from Z = 0.70m up to 2.45m
for s in range(10):
    z = round(0.70 + s * 0.175, 3)
    y_center = -11.45 + s * 0.25
    lines.append(f"box((8.90, {y_center:.3f}, 0.00), (1.45, 0.28, {z + 0.175:.3f}), name='ST2_Main_Step_{s+1}', color=(0.75, 0.78, 0.82, 1.0))")

